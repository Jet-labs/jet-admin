/**
 * Widget Descriptors (F04 canonical contract source).
 *
 * One versioned descriptor per registered widget type. This module is the
 * single source of truth that UI (defaults/examples), API validation and MCP
 * discovery derive from — never the reverse.
 *
 * Each descriptor:
 * - type: registered widget type string (matches WIDGET_TYPES values)
 * - schemaVersion: descriptor version, currently 1 for every type
 * - category: catalogue grouping by user task
 * - tags/searchAliases: catalogue search terms (includes legacy names)
 * - defaults: canonical default config (safe, meaningful — no blank forms)
 * - aliases: legacy/synonym config keys migrated by normalizeWidgetConfig.
 *   Canonical keys always win on conflict. Normalization is idempotent.
 * - templateProps: config keys that accept {{ }} expressions at authoring
 * - required: config keys enforced by validateWidgetConfig
 * - dataKey/stateShape: binding contract (what queries feed, what state holds)
 * - unsupportedEvents/unsupportedMethods: declared-but-not-implemented
 *   capabilities (B17). Configs may still carry them (never dropped), but
 *   only supported entries are advertised to authors/AI.
 * - unsupportedReserved: schema-advertised fields with no renderer effect yet
 * - example: minimal working canonical config (validates + renders bound)
 *
 * Events/method tables themselves live in index.js (WIDGET_EVENT_TYPES /
 * WIDGET_METHODS); `supportedEventsFor` / `supportedMethodsFor` apply the
 * unsupported filters from here.
 */

