CREATE INDEX IF NOT EXISTS {{idx:role_matrix_role}} ON {{table:role_matrix}} (role_key);

CREATE TABLE IF NOT EXISTS {{table:suppliers}} (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  code text NOT NULL UNIQUE,
  status text NOT NULL CHECK (status IN ('active', 'on_hold', 'inactive')),
  contact_name text,
  email text,
  phone text,
  payment_terms text NOT NULL CHECK (payment_terms IN ('net_30', 'net_45', 'net_60', 'prepaid')),
  lead_time_days integer,
  tax_id text,
  address text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

CREATE INDEX IF NOT EXISTS {{idx:suppliers_status}} ON {{table:suppliers}} (status);

CREATE INDEX IF NOT EXISTS {{idx:suppliers_payment_terms}} ON {{table:suppliers}} (payment_terms);

CREATE INDEX IF NOT EXISTS {{idx:suppliers_deleted}} ON {{table:suppliers}} (deleted_at);

CREATE INDEX IF NOT EXISTS {{idx:suppliers_label}} ON {{table:suppliers}} (name);

