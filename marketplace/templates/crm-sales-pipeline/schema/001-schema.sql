-- CRM & Sales Pipeline — template schema
-- Idempotent DDL. Physical table names are resolved at install time.

-- Support tables shared by every app template.
CREATE TABLE IF NOT EXISTS {{table:staff}} (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name text NOT NULL,
  email text NOT NULL,
  role_key text NOT NULL,
  department text,
  job_title text,
  phone text,
  city text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS {{idx:staff_role}} ON {{table:staff}} (role_key);
CREATE UNIQUE INDEX IF NOT EXISTS {{idx:staff_email}} ON {{table:staff}} (email);

CREATE TABLE IF NOT EXISTS {{table:lookups}} (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category text NOT NULL,
  code text NOT NULL,
  label text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  UNIQUE (category, code)
);
CREATE INDEX IF NOT EXISTS {{idx:lookups_category}} ON {{table:lookups}} (category);

CREATE TABLE IF NOT EXISTS {{table:audit_log}} (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity text NOT NULL,
  entity_id integer,
  action text NOT NULL,
  actor text NOT NULL DEFAULT 'system',
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS {{idx:audit_entity}} ON {{table:audit_log}} (entity, entity_id);
CREATE INDEX IF NOT EXISTS {{idx:audit_created}} ON {{table:audit_log}} (created_at DESC);

CREATE TABLE IF NOT EXISTS {{table:comments}} (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity text NOT NULL,
  entity_id integer NOT NULL,
  author_id integer REFERENCES {{table:staff}}(id) ON DELETE SET NULL,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE INDEX IF NOT EXISTS {{idx:comments_entity}} ON {{table:comments}} (entity, entity_id);

CREATE TABLE IF NOT EXISTS {{table:attachments}} (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity text NOT NULL,
  entity_id integer NOT NULL,
  file_name text NOT NULL,
  file_url text NOT NULL,
  mime_type text,
  uploaded_by integer REFERENCES {{table:staff}}(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS {{idx:attachments_entity}} ON {{table:attachments}} (entity, entity_id);

CREATE TABLE IF NOT EXISTS {{table:notifications}} (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id integer REFERENCES {{table:staff}}(id) ON DELETE CASCADE,
  title text NOT NULL,
  body text,
  category text NOT NULL DEFAULT 'info',
  is_read boolean NOT NULL DEFAULT false,
  link_page text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS {{idx:notifications_staff}} ON {{table:notifications}} (staff_id, is_read);

CREATE TABLE IF NOT EXISTS {{table:app_config}} (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL,
  config_key text NOT NULL,
