CREATE TABLE IF NOT EXISTS {{table:accounts}} (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_name text NOT NULL,
  industry text NOT NULL CHECK (industry IN ('saas', 'financial_services', 'healthcare', 'manufacturing', 'retail', 'logistics', 'public_sector')),
  tier text NOT NULL CHECK (tier IN ('strategic', 'enterprise', 'mid_market', 'smb')),
  website text,
  phone text,
  city text,
  country text,
  owner_id integer NOT NULL REFERENCES {{table:staff}}(id) ON DELETE SET NULL,
  annual_revenue numeric(14,2),
  health_score integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

