CREATE TABLE IF NOT EXISTS {{table:skus}} (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku_code text NOT NULL UNIQUE,
  name text NOT NULL,
  category text NOT NULL CHECK (category IN ('fasteners', 'electronics', 'mechanical', 'packaging', 'safety', 'chemicals')),
  uom text NOT NULL CHECK (uom IN ('each', 'box', 'case', 'pallet', 'kg', 'liter')),
  unit_cost numeric(14,2),
  abc_class text NOT NULL CHECK (abc_class IN ('A', 'B', 'C')),
  is_active boolean DEFAULT true,
  description text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

